/**
 * Generates tests/golden/raw/ROLE_VARIANCE.md from the committed raw fixtures:
 * for each example and endpoint, which roles see identical content and, where they
 * differ, how many rows / which fields differ.  Pure function of the fixtures.
 *
 *   node scripts/golden/role-variance.mjs
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const RAW = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'tests', 'golden', 'raw');
const ROLES = ['anon', 'testuser', 'testeditor', 'testmanager', 'testadmin'];

const KEYS = {
  schema_entities: ['table_name'],
  'schema_entities.mcp': ['table_name'],
  schema_properties: ['table_name', 'column_name'],
  'schema_properties.mcp': ['table_name', 'column_name'],
  schema_m2m_properties: ['table_name', 'property_name'],
  schema_entity_actions: ['id'],
  'schema_entity_actions.mcp': ['id'],
};

const read = (p) => JSON.parse(readFileSync(p, 'utf8'));

function rowKey(file, row, i) {
  const base = file.replace(/\.[a-z]+$/, '');
  const ks = KEYS[file] ?? KEYS[base];
  if (ks && ks.every((k) => k in row)) return ks.map((k) => row[k]).join('|');
  if (row && typeof row === 'object' && 'id' in row) return `id:${row.id}`;
  return `#${i}`;
}

function diffRows(file, a, b) {
  // a, b are arrays of rows (already ordered). Returns { onlyA, onlyB, changed, fields }
  const ma = new Map(a.map((r, i) => [rowKey(file, r, i), r]));
  const mb = new Map(b.map((r, i) => [rowKey(file, r, i), r]));
  let onlyA = 0, onlyB = 0, changed = 0;
  const fields = new Map();
  for (const [k, r] of ma) {
    if (!mb.has(k)) { onlyA++; continue; }
    const s = mb.get(k);
    let diff = false;
    for (const f of new Set([...Object.keys(r), ...Object.keys(s)])) {
      if (JSON.stringify(r[f]) !== JSON.stringify(s[f])) { diff = true; fields.set(f, (fields.get(f) ?? 0) + 1); }
    }
    if (diff) changed++;
  }
  for (const k of mb.keys()) if (!ma.has(k)) onlyB++;
  return { onlyA, onlyB, changed, fields };
}

const out = [];
out.push('# Role variance in the raw contract captures', '');
out.push('Generated by `node scripts/golden/role-variance.mjs` from the committed fixtures; do not edit by hand.', '');
out.push('For each example and endpoint (default locale), roles are grouped by byte-identical content. When groups differ, the summary compares the lowest-privilege group (usually `anon`) against the highest (`testadmin`): rows only in one side, rows present in both whose fields differ, and which fields differ.', '');

const summary = { endpointsTotal: 0, endpointsVarying: 0 };
const exampleNotes = [];

for (const ex of readdirSync(RAW).sort()) {
  const exDir = join(RAW, ex);
  if (!statSync(exDir).isDirectory()) continue;
  const files = readdirSync(join(exDir, 'anon')).filter((f) => f.endsWith('.json')).sort();
  // union with other roles (status/category RPCs could exist for some roles only)
  const all = new Set(files);
  for (const r of ROLES) for (const f of readdirSync(join(exDir, r))) if (f.endsWith('.json')) all.add(f);
  const rows = [];
  for (const f of [...all].sort()) {
    const name = f.replace(/\.json$/, '');
    const texts = {};
    for (const r of ROLES) {
      try { texts[r] = readFileSync(join(exDir, r, f), 'utf8'); } catch { texts[r] = null; }
    }
    summary.endpointsTotal++;
    const groups = new Map();
    for (const r of ROLES) {
      const k = texts[r] ?? '__ABSENT__';
      groups.set(k, [...(groups.get(k) ?? []), r]);
    }
    if (groups.size === 1) continue;
    summary.endpointsVarying++;
    const grpList = [...groups.entries()].map(([k, rs]) => ({ k, rs }));
    let detail = '';
    const lo = texts.anon, hi = texts.testadmin;
    if (lo !== null && hi !== null && lo !== hi) {
      const a = read(join(exDir, 'anon', f)), b = read(join(exDir, 'testadmin', f));
      if (Array.isArray(a) && Array.isArray(b)) {
        const d = diffRows(name, a, b);
        const fl = [...d.fields.entries()].sort((x, y) => y[1] - x[1]).map(([k, n]) => `${k}(${n})`).join(', ');
        detail = `anon ${a.length} rows vs testadmin ${b.length}; only-anon ${d.onlyA}, only-admin ${d.onlyB}, changed ${d.changed}${fl ? `; fields: ${fl}` : ''}`;
      } else if (a && a.__status !== undefined || b && b.__status !== undefined) {
        detail = `anon status ${a?.__status ?? 200} vs testadmin status ${b?.__status ?? 200}`;
      } else detail = 'non-array content differs';
    } else if (lo === null || hi === null) detail = 'file absent for some roles';
    rows.push({ name, groups: grpList.map((g) => g.rs.join('+')).join(' / '), detail });
  }
  out.push(`## ${ex}`, '');
  if (!rows.length) out.push('No endpoint differs by role.', '');
  else {
    out.push('| Endpoint | Identical-content role groups | anon vs testadmin |', '|---|---|---|');
    for (const r of rows) out.push(`| \`${r.name}\` | ${r.groups} | ${r.detail || ''} |`);
    out.push('');
  }
  const stable = [...all].length - rows.length;
  exampleNotes.push(`${ex}: ${rows.length} of ${[...all].length} endpoints vary by role (${stable} identical for all five).`);
}

out.splice(4, 0, '## Summary', '', ...exampleNotes.map((n) => `- ${n}`), '', `Overall: ${summary.endpointsVarying} of ${summary.endpointsTotal} example-endpoint fixtures vary by role.`, '',
  '## Findings (checked against the tables below)', '',
  '- Confirmed: `schema_entities` CRUD flags (`select`/`insert`/`update`/`delete`) vary by role in every example, and for some examples the row set differs too (entities without any grant for a role are absent).',
  '- Refuted in part: `schema_properties` rows never differ in field values between roles; what varies is the row SET (columns the role cannot read are absent) and only in the examples where grants differ by role. The `.mcp` ordering variants behave identically.',
  '- Also varies: `rpc.get_current_user_permissions` (every example), `schema_entity_actions.can_execute` (and `.mcp`), and `user_profile_extensions.is_required` in client-intake.',
  '- Never varies by role in any example: `static_text`, `constraint_messages`, `schema_guided_*`, `schema_m2m_properties`, `statuses`, `categories`, `status_transitions`, `photo_gallery_config`, `schema_cache_versions` (masked), and the per-type status/category RPCs, unless listed in the tables below.',
  '');
writeFileSync(join(RAW, 'ROLE_VARIANCE.md'), out.join('\n') + '\n');
console.log(`wrote ROLE_VARIANCE.md (${summary.endpointsVarying}/${summary.endpointsTotal} vary)`);
