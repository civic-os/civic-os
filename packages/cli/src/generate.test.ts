import { mkdirSync, mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { beforeAll, describe, expect, it, vi } from 'vitest';
import { compileWith, defaultColumns } from '@civic-os/core';
import { main } from './cli.js';
import { emitTypes } from './emit.js';
import { generateTypes } from './generate.js';
import { fixtureSource, loadRawSchema } from './load.js';
import { buildModel, prepareContext } from './model.js';
import { buildCore, repoRoot, typecheck, usageFile } from './test-support/typecheck.js';

const POTHOLE = join(repoRoot, 'tests', 'golden', 'raw', 'pothole', 'testadmin');
const raw = await loadRawSchema(fixtureSource(POTHOLE, repoRoot));
const model = buildModel(raw);
const issue = model.entities.find(e => e.name === 'Issue')!;

describe('buildModel (pothole)', () => {
  it('copies the version record and never computes the hash', () => {
    expect(model.schemaHash).toBe(raw.domainVersion.contract_hash);
    expect(model.domainVersion).toBe(raw.domainVersion.domain_version);
    expect(model.source).toBe('tests/golden/raw/pothole/testadmin');
  });

  it('Row has the columns of the default select, without the tsvector or the M:M properties', () => {
    const ctx = prepareContext(raw);
    expect(issue.row.map(c => c.name)).toEqual(defaultColumns(ctx.properties, 'Issue').map(p => p.column_name).sort());
    expect(issue.row.map(c => c.name)).not.toContain('civic_os_text_search');
    expect(issue.row.map(c => c.name)).not.toContain('issue_tags_m2m');
    const select = compileWith('Issue', {}, ctx).select;
    expect(select).not.toContain('civic_os_text_search');
  });

  it('Insert optionality follows default, identity and nullability', () => {
    const col = (n: string) => issue.row.find(c => c.name === n)!;
    expect(col('display_name').optional).toBe(false); // not null, no default
    expect(col('id').optional).toBe(true); // identity
    expect(col('status').optional).toBe(true); // default get_initial_status
    expect(col('description').optional).toBe(true); // nullable
  });

  it('Embedded fields are the fields of the default embed', () => {
    const emb = (n: string) => issue.embedded.find(e => e.column === n)!;
    expect(emb('status').type.fields!.map(f => f.name)).toEqual(['id', 'display_name', 'color', 'status_key']);
    expect(emb('created_user').type.fields!.map(f => f.name)).toEqual(['id', 'display_name', 'full_name', 'phone', 'email']);
    expect(emb('work_package').type.nullable).toBe(true);
    expect(issue.embedded.find(e => e.column === 'location')).toBeUndefined(); // the geography alias is a string, not an embed
  });

  it('Relations are the with graph: FK one, inverse and M:M many; system columns are not relations', () => {
    expect(issue.relations).toEqual([
      { key: 'WorkDetail', kind: 'many', target: 'WorkDetail' },
      { key: 'issue_tags_m2m', kind: 'many', target: 'Tag', via: 'junction' },
      { key: 'work_package', kind: 'one', target: 'WorkPackage', nullable: true },
    ]);
  });

  it('status keys are the status_key values of the entity status type', () => {
    expect(issue.statusKeyType).toBe('IssueStatusKey');
    expect(issue.statusKeys).toContain('repair_queue');
    expect(model.entities.find(e => e.name === 'Tag')!.statusKeyType).toBeUndefined();
  });
});

describe('emitTypes', () => {
  it('is byte-stable and carries no timestamp', async () => {
    const a = await generateTypes(fixtureSource(POTHOLE, repoRoot));
    const b = await generateTypes(fixtureSource(POTHOLE, repoRoot));
    expect(a.text).toBe(b.text);
    expect(a.text).toMatch(/^\/\* eslint-disable \*\/\n\/\/ Generated by @civic-os\/cli \d+\.\d+\.\d+ /);
    expect(a.text).not.toMatch(/\b20\d\d-\d\d-\d\d\b/);
  });

  it('prints the version constants as literals and the status unions as named types', () => {
    const text = emitTypes(model, 'test 0.0.0');
    expect(text).toContain(`export const SCHEMA_HASH = '${raw.domainVersion.contract_hash}' as const;`);
    expect(text).toContain('export const DOMAIN_VERSION = ');
    expect(text).toMatch(/\/\*\* data-derived \*\/\nexport type IssueStatusKey = '/);
  });

  it('binds core defineQuery to the generated Database exactly once', () => {
    const text = emitTypes(model, 'test 0.0.0');
    expect(text.match(/^import \{ defineQuery as defineCoreQuery \} from '@civic-os\/core';$/gm)).toHaveLength(1);
    expect(text.match(/^export function defineQuery<E extends keyof Database\['entities'\] & string>\(\) \{$/gm)).toHaveLength(1);
    expect(text).toContain('  return defineCoreQuery<Database, E>();');
    expect(text.indexOf('export interface Database')).toBeLessThan(text.indexOf('export function defineQuery'));
  });

  it('keeps the bound helper valid for an instance with no entities', () => {
    const text = emitTypes({ ...model, entities: [] }, 'test 0.0.0');
    expect(text).toContain('export interface Database {\n  entities: {\n  };\n}');
    expect(text.match(/export function defineQuery</g)).toHaveLength(1);
  });

  it('prints empty members as {} so keyof stays never', () => {
    const text = emitTypes(model, 'test 0.0.0');
    expect(text).toContain('Embedded: {};');
    expect(text).not.toContain('Record<string, never>');
  });

  it('quotes keys that are not identifiers', () => {
    const odd = { ...model, entities: [{ ...issue, name: 'odd-name', row: [{ ...issue.row[0]!, name: 'a b' }] }] };
    const text = emitTypes(odd, 'test 0.0.0');
    expect(text).toContain('"odd-name": {');
    expect(text).toContain('"a b": ');
  });
});

describe('generated pothole types', () => {
  beforeAll(() => buildCore(), 120_000);

  it.each([false, true])('type-check against core with exactOptionalPropertyTypes=%s', async exact => {
    const { text } = await generateTypes(fixtureSource(POTHOLE, repoRoot));
    const usage = usageFile('Issue', 'status') + `
const full = defineQuery<Database, 'Issue'>()({ select: ['id', 'status'], with: { work_package: { columns: ['display_name'] }, WorkDetail: true } });
export declare const full_: QueryResult<Database, 'Issue', typeof full>;
export const key: import('./database.js').IssueStatusKey = full_.status.status_key;
export const wp: string | undefined = full_.work_package?.display_name;
export const n: number = full_.WorkDetail[0]!.id;

// the bound helper infers what the unbound form infers
import { defineQuery as bound } from './database.js';
const viaBound = bound<'Issue'>()({ select: ['id', 'status'], with: { work_package: { columns: ['display_name'] }, WorkDetail: true } });
export declare const viaBound_: QueryResult<Database, 'Issue', typeof viaBound>;
export const sameInference: typeof full_ = viaBound_;
export const sameInferenceBack: typeof viaBound_ = full_;
export const boundKey: import('./database.js').IssueStatusKey = viaBound_.status.status_key;
// @ts-expect-error the bound form rejects an unknown entity
bound<'Nope'>();
// @ts-expect-error the bound form rejects an unknown column
bound<'Issue'>()({ select: ['no_such_column'] });
`;
    const r = typecheck({ 'database.ts': text, 'usage.ts': usage }, exact);
    expect(r.output).toBe('');
    expect(r.ok).toBe(true);
  }, 120_000);
});

describe('civic-os gen types', () => {
  it('writes the same bytes through --out as the library returns', async () => {
    const out = join(mkdtempSync(join(tmpdir(), 'civic-os-out-')), 'database.ts');
    expect(await main(['gen', 'types', '--from-fixture', POTHOLE, '--out', out])).toBe(0);
    expect(readFileSync(out, 'utf8')).toBe((await generateTypes(fixtureSource(POTHOLE, process.cwd()))).text.replace(/^\/\/ Source: .*$/m, `// Source: ${fixtureSource(POTHOLE).label}`));
  });

  it('fails with a message, not a stack, when the instance predates the domain version view', async () => {
    const dir = mkdtempSync(join(tmpdir(), 'civic-os-old-'));
    mkdirSync(dir, { recursive: true });
    expect(await main(['gen', 'types', '--from-fixture', dir])).toBe(1);
  });

  it('rejects a missing or doubled input', async () => {
    expect(await main(['gen', 'types'])).toBe(2);
    expect(await main(['gen', 'types', '--from-fixture', 'a', '--url', 'b'])).toBe(2);
    expect(await main(['gen', 'other'])).toBe(2);
  });

  it('answers an unknown option or a missing option value with usage, not a stack', async () => {
    const stderr = vi.spyOn(process.stderr, 'write').mockImplementation(() => true);
    try {
      expect(await main(['gen', 'types', '--from-fixure', POTHOLE])).toBe(2);
      expect(await main(['gen', 'types', '--url'])).toBe(2);
      expect(String(stderr.mock.calls[0]![0])).toContain('--from-fixure');
    } finally {
      stderr.mockRestore();
    }
  });
});
