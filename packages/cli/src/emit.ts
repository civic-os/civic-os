import type { CodegenModel, EntityModel, FieldNode, TypeNode } from './model.js';

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (name: string): string => (IDENT.test(name) ? name : JSON.stringify(name));
const lit = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

// An empty member prints as `{}`, never `Record<string, never>`: `keyof Record<string, never>` is `string`, which
// would make every column an embedded one in the typed query API.
function printType(t: TypeNode, indent: string): string {
  let base: string;
  if (t.fields) {
    base = t.fields.length
      ? `{\n${t.fields.map(f => `${indent}  ${printField(f, `${indent}  `)};`).join('\n')}\n${indent}}`
      : '{}';
  } else {
    base = t.text ?? 'unknown';
  }
  if (t.many) base = `Array<${base}>`;
  return t.nullable ? `${base} | null` : base;
}

function printField(f: FieldNode, indent: string): string {
  return `${key(f.name)}: ${printType(f.type, indent)}`;
}

function printEntity(e: EntityModel): string {
  const i = '      ';
  const out: string[] = [];
  const block = (title: string, lines: string[]): void => {
    out.push(lines.length ? `${i}${title}: {\n${lines.join('\n')}\n${i}};` : `${i}${title}: {};`);
  };

  block('Row', e.row.flatMap(c => [
    ...(c.note ? [`${i}  /** ${c.note} */`] : []),
    `${i}  ${key(c.name)}: ${printType(c.type, `${i}  `)};`,
  ]));
  block('Insert', e.row.filter(c => !c.generated).map(c => `${i}  ${key(c.name)}${c.optional ? '?' : ''}: ${printType(c.type, `${i}  `)};`));
  out.push(`${i}Update: Partial<Database['entities'][${lit(e.name)}]['Insert']>;`);
  block('Embedded', e.embedded.map(c => `${i}  ${key(c.column)}: ${printType(c.type, `${i}  `)};`));
  block('Relations', e.relations.map(r => `${i}  ${key(r.key)}: { kind: ${lit(r.kind)}; target: ${lit(r.target)}${r.kind === 'one' ? `; nullable: ${r.nullable}` : ''}${r.via ? `; via: ${lit(r.via)}` : ''} };`));
  out.push(`${i}Statuses: ${e.statusKeyType ?? 'never'};`);
  block('Actions', e.actions.map(a => {
    const params = a.params.map(p => `${key(p.name)}${p.required ? '' : '?'}: ${p.type}`).join('; ');
    return `${i}  ${key(a.name)}: { params: ${params ? `{ ${params} }` : '{}'} };`;
  }));
  out.push(`${i}Features: { ${Object.entries(e.features).map(([k, v]) => `${k}: ${v}`).join('; ')} };`);
  return `    ${key(e.name)}: {\n${out.join('\n')}\n    };`;
}

/**
 * Print the model as one TypeScript file. Byte-stable: the model is already sorted and nothing here reads a
 * clock or the environment.
 *
 * @consumer tooling
 */
export function emitTypes(model: CodegenModel, generator: string): string {
  const lines: string[] = [
    '/* eslint-disable */',
    `// Generated by ${generator} (civic-os gen types). Do not edit.`,
    `// Source: ${model.source}`,
    '//',
    '// GeoPoint and GeoPolygon columns are typed `string`: the default select returns the `<column>_text`',
    '// WKT string aliased to the column. A `*StatusKey` union is data-derived: it lists the status_key values',
    '// the instance had when this file was generated.',
    '',
    "import { defineQuery as defineCoreQuery } from '@civic-os/core';",
    '',
    `export const DOMAIN_VERSION = ${lit(model.domainVersion)} as const;`,
    // null when the instance cannot derive its framework release from the Sqitch registry
    `export const FRAMEWORK_VERSION = ${model.frameworkVersion === null ? 'null' : `${lit(model.frameworkVersion)} as const`};`,
    `export const SCHEMA_HASH = ${lit(model.schemaHash)} as const;`,
    '',
    'export interface Database {',
    '  entities: {',
    ...model.entities.map(printEntity),
    '  };',
    '}',
    '',
    "/** Core's defineQuery bound to this Database, so a query names only its entity: `defineQuery<E>()({ select: [...] })`. */",
    "export function defineQuery<E extends keyof Database['entities'] & string>() {",
    '  return defineCoreQuery<Database, E>();',
    '}',
  ];
  for (const e of model.entities) {
    if (!e.statusKeyType) continue;
    lines.push('', '/** data-derived */', `export type ${e.statusKeyType} = ${e.statusKeys.length ? e.statusKeys.map(lit).join(' | ') : 'never'};`);
  }
  return `${lines.join('\n')}\n`;
}
